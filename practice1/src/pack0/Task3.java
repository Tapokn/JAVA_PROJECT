package pack0;

public class Task3 {
    // Написать программу, в результате которой массив чисел создается с
    //помощью инициализации (как в Си) вводится и считается в цикле сумма
    //элементов целочисленного массива, а также среднее арифметическое его
    //элементов результат выводится на экран. Использовать цикл for.
    public static void solve() {
        int[] numbers = {1, 2, 99, 8, 67};
        int sum = 0;

        for (int i = 0; i < numbers.length; i++) { // length это поле!!! у массива, а у сторки - метод. Массив в Java — это встроенная структура языка, у него есть ровно одно поле length, доступное только для чтения. Изменить длину массива нельзя, только создав новый массив.
            sum += numbers[i];
        }

        double average = (double) sum / numbers.length; // перед делением приведение переменой sum к типу дабл, чтобы было не целочисленное деление, а был виден остаток.

        System.out.println("Массив: " + java.util.Arrays.toString(numbers)); // Метод Arrays.toString(int[]) проходит по массиву и собирает строку вида [элемент1, элемент2, ...]., иначе я получаю адрес памяти объекта вроде [I@1b6d3586 (это хеш-код адреса)
        // System.out.println(java.util.Arrays.toString(arr));   // работает без import, тк написали полное название пакета, откуад он взядся( java.util)
        System.out.println("Сумма: " + sum);
        System.out.printf("Среднее арифметическое: " +  average); // можно добавить аргумент "Среднее арифметическое: %.3f%n" (%.3f%n - где 3 это скок знаков оставить, а %n это перевод на новую строку
    }
    public static void main(String[] args) {
        solve();
    }
}