package pack0;


public class Task6 {
    // Написать программу, в результате работы которой выводятся на экран
    //первые 10 чисел гармонического ряда (форматировать вывод).
    public static void solve() {
        // Гармонический ряд: 1, 1/2, 1/3, 1/4, ...
        // i — знаменатель, меняется от 1 до 10
        System.out.println("Первые 10 членов гармонического ряда:");
        for (int i = 1; i <= 10; i++) { // начинаем с 1, потому что на 0 делить нельзя
            double term = 1.0 / i; // 1.0 — вещественное число, поэтому деление не целочисленное
            System.out.printf("%.5f%n", term); // %.5f — 5 знаков после запятой, %n — перевод строки
        }
    }

    public static void main(String[] args) {
        solve();
    }
}